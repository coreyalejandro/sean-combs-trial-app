// Types for src/data/trial_days.json (the final research file, copied unchanged).
// Shape: { case, numbering_rule, days[28], verdict }.

export type Confidence = 'high' | 'medium' | 'low'

export interface Source {
  id: string
  title: string
  outlet: string
  url: string
  date: string
  note: string
  opened_this_pass: boolean
}

export interface Witness {
  order: number | string
  name: string
  role?: string
  exam?: string
}

/** One reported figure. `value` is a number, or text such as "8-10", "~190", "2016-03-05". */
export interface ReportedNumber {
  value: number | string
  unit: string
  what: string
  /** Free text, e.g. "pbs_ap | also confirmed: ABC, CBS". Use resolveSources() to turn it into Source records. */
  source: string
  /** Outlet families that reported it. */
  outlets: string[]
  confidence: Confidence
}

export interface DayConfidence {
  level: Confidence
  summary: string
}

export interface TrialDay {
  day: number
  date: string
  weekday: string
  summary: string
  witnesses: Witness[]
  exhibits: string[]
  numbers: ReportedNumber[]
  locations: string[]
  people: string[]
  legal_events: string[]
  sources: Source[]
  discrepancies: string[]
  single_sourced: string[]
  key_points: string[]
  viz_ideas: string[]
  outlet_families: string[]
  confidence: DayConfidence
  day_label: string
  verification_note?: string
  alt_day_labels?: string[]
  calendar_note?: string
}

export interface VerdictPhase {
  date: string
  label: string
  facts: string[]
  confidence: Confidence
}

export interface Verdict {
  title: string
  case: string
  content_note: string
  summary: string
  phases: VerdictPhase[]
  numbers: ReportedNumber[]
  discrepancies: string[]
  single_sourced: string[]
  viz_ideas: string[]
  sources: Source[]
  verification_note: string
  outlet_families: string[]
  confidence: DayConfidence
  day: 'verdict'
}

export interface TrialData {
  case: string
  numbering_rule: string
  days: TrialDay[]
  verdict: Verdict
}

/** Scaffold-owned shared table: src/data/shared/charges.json */
export interface Charge {
  count: number
  short: string
  plain: string
  person: string | null
  outcome: 'guilty' | 'not guilty'
  source_ids: string[]
}

export type WitnessGroup =
  | 'named-in-charges'
  | 'described-harm'
  | 'eyewitness'
  | 'former-staff'
  | 'police-and-agents'
  | 'records-and-analysis'
  | 'expert'

/** Scaffold-owned shared table: src/data/shared/witnesses.json (generated by scripts/build-witnesses.ts). */
export interface WitnessRecord {
  id: string
  /** The only name the app may display. For Mia and Jane this is the pseudonym. */
  display_name: string
  pseudonym: boolean
  /** Raw names exactly as they appear in trial_days.json, used to match day records. */
  raw_names: string[]
  first_day: number
  days: number[]
  group: WitnessGroup
  role: string
  immunity: boolean
}
